#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const cwd = process.cwd();
const rulesPath = path.join(cwd, ".agents", "core", "AGENT_RULES.md");

if (!fs.existsSync(rulesPath)) {
  console.error("Missing .agents/core/AGENT_RULES.md");
  process.exit(1);
}

const rules = fs.readFileSync(rulesPath, "utf8").trim();
const header = "<!-- GENERATED BY .agents/bootstrap.mjs. Edit .agents/, not this file. -->\n\n";

function writeFile(rel, content) {
  const out = path.join(cwd, rel);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  if (fs.existsSync(out) && fs.readFileSync(out, "utf8") === content) return;
  fs.writeFileSync(out, content);
}

writeFile("AGENTS.md", header + `# Project Agent Instructions

The canonical project policy lives under \`.agents/\`.

For non-trivial work:
- follow the rules below,
- use installed pstack workflow when available,
- use \`.agents/skills/code-quality/SKILL.md\` for non-trivial implementation, refactor, debugging, integration, migration, performance, and substantial review work,
- use project-owned skills when their triggers apply,
- use \`.agents/skills/semantic-architecture/SKILL.md\` when architectural intent or system semantics may change,
- treat \`.agents/architecture/\` as the authoritative hierarchical statement of architectural intent,
- progressively load only the architecture path relevant to the task.

## Canonical rules

${rules}
`);

writeFile("CLAUDE.md", header + `# Agent Instructions

Read and follow \`AGENTS.md\`.

Use project-local skills under \`.claude/skills/\` when available.
Use the code-quality skill for non-trivial engineering work.
For architectural work, also use semantic-architecture and progressively inspect \`.agents/architecture/\`.
`);

writeFile("GEMINI.md", header + `# Agent Instructions

Read and follow \`AGENTS.md\`.

Use \`.agents/skills/code-quality/SKILL.md\` for non-trivial engineering work.
For architectural work, also use \`.agents/skills/semantic-architecture/SKILL.md\` and progressively inspect \`.agents/architecture/\`.
`);

writeFile(".cursor/rules/00-project-agents.mdc", `---
description: Canonical repository engineering instructions
alwaysApply: true
---

Read and follow \`AGENTS.md\`.

Use installed pstack as the primary non-trivial engineering workflow.
Use \`.agents/skills/code-quality/SKILL.md\` for detailed engineering quality constraints.
For architectural work, also use \`.agents/skills/semantic-architecture/SKILL.md\` and progressively inspect the relevant path under \`.agents/architecture/\`.
`);
